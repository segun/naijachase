// Shrinks the GLB files in public/assets/3d (texture resize, duplicate/unused data removed) and keeps a record of what is done.
//   pnpm assets:optimize            optimise every file that is new or changed since the last run
//   pnpm assets:optimize --dry-run  show what would happen without touching anything
// Originals are copied once to web/asset-originals/ (not served, not committed). dev/asset-state.json remembers what was processed
// (by file hash), so running again only handles new files. docs/3d-asset-progress.md is rewritten each run.
// Vertex data is quantised (KHR_mesh_quantization, supported by Babylon.js).
// No Draco/Meshopt is used on purpose: Babylon.js would need to download a decoder for them.
// @ts-nocheck
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import sharp from "sharp";
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, prune, quantize, textureCompress } from "@gltf-transform/functions";

const here = path.dirname(new URL(import.meta.url).pathname);
const web = path.resolve(here, "..");
const root = path.join(web, "public/assets/3d");
const backup = path.join(web, "asset-originals");
const statePath = path.join(here, "asset-state.json");
const progressPath = path.resolve(web, "../docs/3d-asset-progress.md");
const promptsPath = path.resolve(web, "../docs/3d-generator-prompts.md");
const dryRun = process.argv.includes("--dry-run");

// Close-up assets keep 2K textures; everything else is seen small and gets 1K.
const KEEP_2K = [/^characters\/avatars\//, /^vehicles\/car_player_runabout\.glb$/, /^vehicles\/bus_danfo\.glb$/];
const sizeFor = rel => (KEEP_2K.some(r => r.test(rel)) ? 2048 : 1024);

const walk = dir => (!fs.existsSync(dir) ? [] : fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
  const full = path.join(dir, e.name);
  return e.isDirectory() ? walk(full) : e.name.endsWith(".glb") ? [full] : [];
})).sort();
const sha = file => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const mb = n => (n / 1e6).toFixed(2);

const state = fs.existsSync(statePath) ? JSON.parse(fs.readFileSync(statePath, "utf8")) : {};
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const files = walk(root);
let done = 0, skipped = 0, failed = 0;

for (const file of files) {
  const rel = path.relative(root, file).split(path.sep).join("/");
  const before = fs.statSync(file).size;
  if (state[rel]?.sha === sha(file)) { skipped++; continue; }
  const limit = sizeFor(rel);
  if (dryRun) { console.log(`would optimise ${rel} (${mb(before)} MB, textures up to ${limit}px)`); continue; }
  try {
    const copy = path.join(backup, rel);
    if (!fs.existsSync(copy)) { fs.mkdirSync(path.dirname(copy), { recursive: true }); fs.copyFileSync(file, copy); }
    const doc = await io.read(copy);
    await doc.transform(dedup(), prune(), textureCompress({ encoder: sharp, resize: [limit, limit], quality: 82 }), quantize());
    await io.write(file, doc);
    const after = fs.statSync(file).size;
    state[rel] = { sha: sha(file), textureLimit: limit, beforeBytes: before, afterBytes: after, optimizedOn: new Date().toISOString().slice(0, 10) };
    console.log(`${rel}  ${mb(before)} MB → ${mb(after)} MB`);
    done++;
  } catch (e) {
    failed++; console.error(`FAILED ${rel}: ${e.message}`);
  }
}
if (dryRun) process.exit(0);
for (const rel of Object.keys(state)) if (!fs.existsSync(path.join(root, rel))) delete state[rel];
fs.writeFileSync(statePath, JSON.stringify(state, null, 2) + "\n");

// ---- progress note ----
const present = new Set(files.map(f => path.basename(f)));
const expected = fs.existsSync(promptsPath)
  ? [...new Set([...fs.readFileSync(promptsPath, "utf8").matchAll(/\|\s*[\d.]+\s*\|\s*`([a-z0-9_]+\.glb)`/g)].map(m => m[1]))]
  : [];
const groups = {};
for (const f of files) {
  const rel = path.relative(root, f).split(path.sep).join("/");
  const g = rel.split("/").slice(0, rel.startsWith("characters/") ? 2 : 1).join("/");
  (groups[g] ||= []).push(rel);
}
const all = Object.values(state);
const totalBefore = all.reduce((n, s) => n + s.beforeBytes, 0), totalAfter = all.reduce((n, s) => n + s.afterBytes, 0);
const missing = expected.filter(n => !present.has(n));
const lines = [
  "# 3D asset progress",
  "",
  "Generated by `pnpm assets:optimize` in `web/` (do not edit by hand; it is rewritten on every run).",
  "",
  "**How to continue:** save new GLB files into `web/public/assets/3d/<folder>/` using the names in [3d-generator-prompts.md](./3d-generator-prompts.md),",
  "check them on `http://127.0.0.1:4173/dev-assets.html` (run `pnpm dev`), then run `pnpm assets:optimize`. Only new or changed files are processed.",
  "Originals are kept in `web/asset-originals/` (not served, not committed). The machine-readable record is `web/dev/asset-state.json`.",
  "",
  `Last run: ${new Date().toISOString().slice(0, 10)}. Files present: **${files.length}**, optimised: **${all.length}**, still to make from the prompt list: **${missing.length}** of ${expected.length}.`,
  `Total size of optimised files: ${mb(totalBefore)} MB → ${mb(totalAfter)} MB.`,
  "",
  "Texture sizes: player avatars, the player's car and the danfo keep 2K; everything else is 1K.",
  "",
  "## Done (present and optimised)",
  ""
];
for (const [g, rels] of Object.entries(groups)) {
  lines.push(`### ${g} (${rels.length})`, "");
  for (const rel of rels) {
    const s = state[rel];
    lines.push(`- [x] \`${path.basename(rel)}\`${s ? ` ${mb(s.beforeBytes)} → ${mb(s.afterBytes)} MB (${s.textureLimit}px)` : " (not optimised yet)"}`);
  }
  lines.push("");
}
lines.push("## Still to make (names from the prompt list)", "");
for (const n of missing) lines.push(`- [ ] \`${n}\``);
lines.push("");
fs.writeFileSync(progressPath, lines.join("\n"));
console.log(`\nOptimised ${done}, already done ${skipped}, failed ${failed}. Note written to docs/3d-asset-progress.md`);
